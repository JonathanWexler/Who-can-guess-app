// Packs index.html + the photos, face cut-outs and Manny's song into
// dist/_worker.js: one self-contained script, deployed with
// `npx wrangler deploy` from this folder (see wrangler.jsonc).
const fs = require('node:fs');
const path = require('node:path');
const dir = __dirname;
const types = { '.jpg': 'image/jpeg', '.png': 'image/png', '.mp3': 'audio/mpeg' };
const files = {};
for (const f of fs.readdirSync(dir)) {
  if (f === 'manny.jpg' || f === 'song.mp3' || /^(face\d*|maze)\.png$/.test(f)) {
    files['/' + f] = [types[path.extname(f)], fs.readFileSync(path.join(dir, f)).toString('base64')];
  }
}
const html = fs.readFileSync(path.join(dir, 'index.html'), 'utf8');
const runtime = fs.readFileSync(path.join(dir, 'worker-template.js'), 'utf8');
const out = `// Generated by build-worker.js — do not edit.\nconst HTML = ${JSON.stringify(html)};\nconst FILES = ${JSON.stringify(files)};\n${runtime}`;
fs.mkdirSync(path.join(dir, 'dist'), { recursive: true });
fs.writeFileSync(path.join(dir, 'dist', '_worker.js'), out);
console.log(`wrote dist/_worker.js ${Math.round(out.length / 1024)} KB with ${Object.keys(files).join(', ')}`);
