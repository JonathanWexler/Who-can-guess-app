// Packs index.html + manny.jpg + face.png into dist/_worker.js: one self-contained
// script, deployed with `npx wrangler deploy` from this folder (see wrangler.jsonc).
const fs = require('node:fs');
const path = require('node:path');
const dir = __dirname;
const html = fs.readFileSync(path.join(dir, 'index.html'), 'utf8');
// Images are embedded as base64 and served from memory.
const images = {
  '/manny.jpg': ['image/jpeg', fs.readFileSync(path.join(dir, 'manny.jpg')).toString('base64')],
  '/face.png': ['image/png', fs.readFileSync(path.join(dir, 'face.png')).toString('base64')],
};
const out = `// Generated by build-worker.js — do not edit.
const HTML = ${JSON.stringify(html)};
const IMAGES = ${JSON.stringify(images)};
const cache = {};
export default {
  fetch(request) {
    const { pathname } = new URL(request.url);
    const img = IMAGES[pathname];
    if (img) {
      cache[pathname] = cache[pathname] || Uint8Array.from(atob(img[1]), (c) => c.charCodeAt(0));
      return new Response(cache[pathname], { headers: { 'content-type': img[0], 'cache-control': 'public, max-age=3600' } });
    }
    if (pathname === '/' || pathname === '/index.html') return new Response(HTML, { headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-cache' } });
    return Response.redirect(new URL('/', request.url).toString(), 302);
  },
};
`;
fs.mkdirSync(path.join(dir, 'dist'), { recursive: true });
fs.writeFileSync(path.join(dir, 'dist', '_worker.js'), out);
console.log('wrote dist/_worker.js', Math.round(out.length / 1024), 'KB');
